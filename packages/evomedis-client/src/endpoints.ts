export type EndpointId = keyof typeof ENDPOINTS;

/** Look up an endpoint by id, or undefined if unknown (caller fails closed). */
export function getEndpoint(id: string): EndpointDef | undefined {
  return (ENDPOINTS as Record<string, EndpointDef>)[id];
}

/** All mutating endpoint ids (the allowlist surface). */
export function mutatingEndpointIds(): string[] {
  return Object.values(ENDPOINTS)
    .filter((e) => e.kind === 'mutate')
    .map((e) => e.id);
}

/** Is this id a known mutating endpoint? */
export function isMutating(id: string): boolean {
  return getEndpoint(id)?.kind === 'mutate';
}
