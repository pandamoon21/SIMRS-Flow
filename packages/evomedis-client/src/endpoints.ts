/**
 * EvoMedis/SIMRS endpoint registry.
 *
 * Safety control #3/#4: mutating endpoints are allowlisted; unknown
 * endpoints are blocked. Every endpoint declares its kind and risk level so
 * the client can fail closed in preview mode.
 *
 * Paths are the literal relative paths used by the legacy v1 CodeIgniter
 * backend (sent as application/x-www-form-urlencoded POSTs, even for reads)
 * and the v2 JSON API. Field casing is preserved exactly — the backend is
 * case-sensitive and inconsistent (txtmedrec vs txtmedrec_pdft vs nomedrec).
 *
 * Source of truth: legacy ranap_v3.py and puisi_v2.js. See docs/api-catalog.md.
 */

export type EndpointKind = 'read' | 'mutate' | 'auth';
export type EndpointRisk = 'low' | 'medium' | 'high' | 'critical';
export type EndpointApi = 'v1' | 'v2' | 'origin';
export type ResponseShape = 'json' | 'text' | 'html' | 'raw';

export interface EndpointDef {
  id: string;
  api: EndpointApi;
  method: 'GET' | 'HEAD' | 'POST';
  path: string;
  kind: EndpointKind;
  riskLevel: EndpointRisk;
  /** Expected response decoding. */
  response: ResponseShape;
  /** Write endpoints that require explicit operator approval. */
  requiresApproval?: boolean;
  /** Human description for the catalog / inspector. */
  description: string;
}

